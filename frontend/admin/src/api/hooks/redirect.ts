import {
  useMutation,
  type UseMutationOptions,
} from '@tanstack/react-query';
import {
  type contentservicev1_CreateRedirectRequest,
  type contentservicev1_DeleteRedirectRequest,
  type contentservicev1_Redirect,
  type contentservicev1_UpdateRedirectRequest,
} from '@/api/generated/admin/service/v1';
import { apiClient } from '@/api/client';
import { type PaginationQuery } from '@/core/transport/rest';

// ==============================
// URL 重定向管理
// ==============================

export function useRedirectsList() {
  return useMutation({
    mutationFn: (query: PaginationQuery) =>
      apiClient.redirectService.List(query.toRawParams()),
  });
}

export function useCreateRedirect(
  options?: UseMutationOptions<contentservicev1_Redirect, Error, contentservicev1_CreateRedirectRequest>,
) {
  return useMutation({
    mutationFn: (req) => apiClient.redirectService.Create(req),
    ...options,
  });
}

export function useUpdateRedirect(
  options?: UseMutationOptions<contentservicev1_Redirect, Error, contentservicev1_UpdateRedirectRequest>,
) {
  return useMutation({
    mutationFn: (req) => apiClient.redirectService.Update(req),
    ...options,
  });
}

export function useDeleteRedirect(
  options?: UseMutationOptions<Record<string, never>, Error, contentservicev1_DeleteRedirectRequest>,
) {
  return useMutation({
    mutationFn: (req) => apiClient.redirectService.Delete(req),
    ...options,
  });
}

/** 导出 nginx 重定向配置（边缘层直跳，绕过后端）：双 map + return 片段 */
export function redirectsToNginxMap(items: contentservicev1_Redirect[]): string {
  const enabled = items.filter((x) => x.enabled);
  const lines = [
    '# Generated by GoWind Content Hub - do not edit manually',
    '# include 本文件后在 server 块内追加：',
    '#   if ($redirect_code != "0") { return $redirect_code $redirect_target; }',
    'map $uri $redirect_code {',
    '    default 0;',
  ];
  for (const item of enabled) {
    lines.push(`    ${item.fromPath} ${item.statusCode ?? 301};`);
  }
  lines.push('}');
  lines.push('map $uri $redirect_target {');
  lines.push('    default "";');
  for (const item of enabled) {
    lines.push(`    ${item.fromPath} "${item.toUrl}";`);
  }
  lines.push('}');
  return lines.join('\n');
}
